def stage_upload(filename: str, data: bytes, *, actor: str) -> StagedUpload:
    """Validate an uploaded file and stage it for review.

    Raises ``UploadError`` for uploads that cannot even be staged (too big, not a
    .py/.zip, unreadable archive). Everything else is reported in the returned
    ``StagedUpload`` (``errors`` block activation, ``warnings`` do not).
    """
    if len(data) > settings.max_upload_bytes():
        raise UploadError(f"file too large (limit {settings.max_upload_bytes() // (1024 * 1024)} MB)")
    lower = (filename or "").lower()
    if lower.endswith(".zip"):
        kind = "zip"
    elif lower.endswith(".py"):
        kind = "py"
    else:
        raise UploadError("upload a .py file or a .zip archive")

    cleanup_expired()
    upload_id = uuid.uuid4().hex
    src = upload_src_dir(upload_id)
    staged = StagedUpload(
        upload_id=upload_id,
        created_at=datetime.now(timezone.utc).isoformat(),
        uploaded_by=actor,
        source_kind=kind,
        original_filename=PurePosixPath((filename or "").replace("\\", "/")).name,
        sha256=hashlib.sha256(data).hexdigest(),
        size=len(data),
        suggested_slug=_suggest_slug(filename),
    )
    try:
        if kind == "zip":
            staged.extract_errors, staged.extract_warnings = _extract_zip(data, src)
        else:
            _write_single_py(data, src)
        src.mkdir(parents=True, exist_ok=True)

        # Manifest shipped in the package: it owns identity and credentials.
        manifest_file = next((src / n for n in MANIFEST_FILENAMES if (src / n).is_file()), None)
        if manifest_file is not None:
            staged.manifest_source = "package"
            try:
                manifest = parse_manifest_text(manifest_file.read_text(encoding="utf-8"))
                staged.manifest = manifest.model_dump()
                staged.suggested_slug = manifest.slug
            except (ManifestError, UnicodeDecodeError) as exc:
                msgs = exc.errors if isinstance(exc, ManifestError) else [str(exc)]
                staged.extract_errors.extend(f"{manifest_file.name}: {m}" for m in msgs)

        staged.files = _list_files(src)
        _review(staged, src)
    except Exception:
        discard(upload_id)
        raise
    _save_state(staged)
    return staged


def submit_manifest(upload_id: str, data: Dict[str, Any]) -> StagedUpload:
    """Attach the manifest filled in the admin-ui form (uploads without aion-mcp.yaml).

    The generated ``aion-mcp.yaml`` is written into the package so it travels with
    the code (and appears in the archived versions). Refused when the package ships
    its own manifest: that file is owned by the developers, not by the form.
    Raises ``ManifestError`` (field errors) or ``ValueError``.
    """
    staged = load_staged(upload_id)
    if staged.manifest_source == "package":
        raise ValueError("this package ships its own aion-mcp.yaml: edit the file and upload again")
    manifest = parse_manifest_data(data)
    src = upload_src_dir(upload_id)
    for name in MANIFEST_FILENAMES:
        (src / name).unlink(missing_ok=True)
    (src / MANIFEST_FILENAMES[0]).write_text(manifest.to_yaml(), encoding="utf-8")
    staged.manifest = manifest.model_dump()
    staged.manifest_source = "form"
    staged.files = _list_files(src)
    _review(staged, src)
    _save_state(staged)
    return staged
