"""Upload validation and staging for customer-built MCP servers.

An upload (single ``.py`` or ``.zip``) is never written into the live server
folder directly. It is extracted into ``mcp_servers/custom/.staging/<upload_id>/src``
and analysed; the admin reviews the result in admin-ui and only then activates it
(``install.activate``).

What is checked here (all reported back to the admin):

- archive safety: size and file-count limits, zip-slip paths, symlinks, encrypted
  entries, a single wrapper folder is unwrapped, caches/VCS folders are skipped,
  ``.env`` files are dropped (credentials go through AION, never in clear on disk);
- the manifest (``aion-mcp.yaml``) and its entrypoint;
- top-level files/folders that would shadow standard-library or MCP modules (the
  server folder comes first on ``sys.path``, so ``json/`` or ``token.py`` breaks it);
- the **variables check**: env vars read by the code (AST) compared with what the
  manifest declares in ``env`` and ``credentials``;
- declared dependencies (requirements.txt / pyproject.toml), normalised for the
  build container of the verification step (``verify``);
- review notes: code reading the whole environment, touching system/AION files,
  running commands, executing dynamic code. These are information for the admin,
  not a security boundary: isolation comes from running the server in its own
  container (see the plan, section 3).

Functions are synchronous (filesystem + CPU work); the admin API runs them in a
worker thread. State of each upload is persisted in ``upload.json`` so it survives
backend reloads.
"""

