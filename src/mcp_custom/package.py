# Folders never extracted: caches, virtualenvs and VCS metadata (the runtime builds
# its own environment; shipping them only wastes space and may carry host paths).
_IGNORED_DIRS = frozenset(
    {
        ".venv",
        "venv",
        "__pycache__",
        ".git",
        ".hg",
        ".svn",
        "node_modules",
        ".mypy_cache",
        ".pytest_cache",
        ".ruff_cache",
        ".idea",
        ".vscode",
        "__MACOSX",
    }
)
_IGNORED_FILES = frozenset({".DS_Store", "Thumbs.db"})
# .env templates are documentation and stay; real .env files hold secrets.
_ENV_TEMPLATE_NAMES = frozenset({".env.example", ".env.sample", ".env.template"})

# Top-level names that must not be shadowed by a package file/folder: the standard
# library plus the libraries every MCP server depends on. "test" is excluded on
# purpose (a common folder name, never imported by a server at runtime).
_SHADOW_EXTRA = frozenset(
    {"mcp", "fastmcp", "pydantic", "pydantic_core", "httpx", "anyio", "starlette", "uvicorn", "yaml", "typing_extensions"}
)
_SHADOW_NAMES = (frozenset(sys.stdlib_module_names) | _SHADOW_EXTRA) - {"test"}

# Variables AION always sets for a custom server: reading them is fine and they are
# not expected in the manifest.
PROVIDED_ENV = frozenset(
    {
        "AION_CURRENT_USER_ID",
        "AION_CURRENT_PROFILE_SLUG",
        "AION_CURRENT_TENANT_ID",
        "AION_CHAT_SESSION_ID",
        "HOME",
        "PATH",
        "TMPDIR",
        "LANG",
    }
)

README_MAX_CHARS = 20_000
MAX_NOTES = 60


@dataclass
class StagedUpload:
    """Everything the admin needs to review an upload before activating it."""

    upload_id: str
    created_at: str
    uploaded_by: str
    source_kind: str  # "py" | "zip"
    original_filename: str
    sha256: str
    size: int
    files: List[Dict[str, Any]] = field(default_factory=list)
    # Validated manifest (dict) or None while the admin still has to fill the form.
    manifest: Optional[Dict[str, Any]] = None
    # "package": aion-mcp.yaml shipped in the zip (read-only in the UI);
    # "form": generated by AION from the admin-ui form; None: not provided yet.
    manifest_source: Optional[str] = None
    entrypoint: Optional[str] = None
    suggested_slug: str = ""
    errors: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    env_used: List[str] = field(default_factory=list)
    env_check: Dict[str, List[str]] = field(default_factory=dict)
    # Kept for uploads staged by older versions: modules are now checked for real by
    # the verification probe inside the jail (see ``verify``), not on the backend.
    missing_modules: List[str] = field(default_factory=list)
    # Dependency specs declared by the package (requirements.txt or pyproject.toml).
    requirements: List[str] = field(default_factory=list)
    review_notes: List[Dict[str, Any]] = field(default_factory=list)
    has_requirements: bool = False
    readme: Optional[str] = None
    # Set when the slug already belongs to a custom server: {slug, current_version, same_version}.
    update_of: Optional[Dict[str, Any]] = None
    # Problems found while extracting (kept apart because manifest checks are re-run
    # when the admin submits the form, extraction is not).
    extract_errors: List[str] = field(default_factory=list)
    extract_warnings: List[str] = field(default_factory=list)
    # Verification inside the jail (``verify.run_verification``): dependency build and
    # probe. {status: pending|running|ok|failed, log, error, tools, deps_key, ...}
    build: Dict[str, Any] = field(default_factory=dict)

    @property
    def status(self) -> str:
        """Lifecycle of the upload, as shown in admin-ui.

        ``invalid`` (blocking errors) -> ``needs_manifest`` (form required) ->
        ``verifying`` (dependency build + probe in the jail) -> ``ready`` or
        ``verify_failed``. Only ``ready`` can be activated.
        """
        if self.errors:
            return "invalid"
        if self.manifest is None:
            return "needs_manifest"
        build_status = (self.build or {}).get("status")
        if build_status == "ok":
            return "ready"
        if build_status == "failed":
            return "verify_failed"
        return "verifying"

    def to_public(self) -> Dict[str, Any]:
        """JSON view returned by the admin API (internal extraction lists folded in)."""
        data = asdict(self)
        data.pop("extract_errors", None)
        data.pop("extract_warnings", None)
        data["status"] = self.status
        return data


class UploadError(ValueError):
    """Upload rejected before staging (size, format, unreadable archive)."""


class UploadNotFound(LookupError):
    """Unknown, expired or malformed upload id."""


# ───────────────────────── staging helpers ─────────────────────────


def _upload_dir(upload_id: str) -> Path:
    if not _UPLOAD_ID_RE.match(upload_id or ""):
        raise UploadNotFound(upload_id)
    return staging_root() / upload_id


def upload_src_dir(upload_id: str) -> Path:
    """Folder holding the extracted code of an upload."""
    return _upload_dir(upload_id) / "src"


def _save_state(staged: StagedUpload) -> None:
    path = _upload_dir(staged.upload_id) / "upload.json"
    path.write_text(json.dumps(asdict(staged), indent=2, ensure_ascii=False), encoding="utf-8")


def load_staged(upload_id: str) -> StagedUpload:
    """Read the persisted review state of an upload. Raises ``UploadNotFound``."""
    path = _upload_dir(upload_id) / "upload.json"
    if not path.is_file():
        raise UploadNotFound(upload_id)
    data = json.loads(path.read_text(encoding="utf-8"))
    return StagedUpload(**data)


def discard(upload_id: str) -> None:
    """Delete an upload that will not be activated (no-op when already gone)."""
    target = _upload_dir(upload_id)
    if target.is_dir():
        shutil.rmtree(target, ignore_errors=True)


def cleanup_expired(now: Optional[float] = None) -> int:
    """Remove uploads older than the staging TTL; returns how many were removed.

    Called at every new upload so abandoned reviews do not pile up on disk.
    """
    root = staging_root()
    if not root.is_dir():
        return 0
    limit = (now or time.time()) - settings.staging_ttl_seconds()
    removed = 0
    for entry in root.iterdir():
        try:
            if entry.is_dir() and entry.stat().st_mtime < limit:
                shutil.rmtree(entry, ignore_errors=True)
                removed += 1
        except OSError:
            continue
    return removed


# ───────────────────────── extraction ─────────────────────────


def _suggest_slug(filename: str) -> str:
    """Slug proposal from the uploaded file name (``CRM-Interno v2.zip`` -> ``crm_interno_v2``)."""
    stem = PurePosixPath(filename.replace("\\", "/")).name.rsplit(".", 1)[0]
    slug = re.sub(r"[^a-z0-9_]+", "_", stem.lower()).strip("_")
    if not slug or not slug[0].isalpha():
        slug = f"mcp_{slug}" if slug else "mcp_custom_server"
    return slug[:41]


def _safe_member_path(name: str) -> Optional[PurePosixPath]:
    """Normalised relative path of a zip member, or None when it escapes the folder."""
    raw = name.replace("\\", "/")
    if "\0" in raw or raw.startswith("/") or re.match(r"^[A-Za-z]:", raw):
        return None
    parts = [p for p in raw.split("/") if p not in ("", ".")]
    if not parts or any(p == ".." for p in parts):
        return None
    return PurePosixPath(*parts)


def _is_env_file(name: str) -> bool:
    return (name == ".env" or name.startswith(".env.")) and name not in _ENV_TEMPLATE_NAMES


def _extract_zip(data: bytes, dest: Path) -> Tuple[List[str], List[str]]:
    """Extract a zip into ``dest`` applying the safety rules; returns (errors, warnings)."""
    errors: List[str] = []
    warnings: List[str] = []
    try:
        archive = zipfile.ZipFile(io.BytesIO(data))
    except zipfile.BadZipFile:
        raise UploadError("the file is not a valid zip archive")

    # First pass: decide what is extracted, without touching the disk.
    kept: List[Tuple[zipfile.ZipInfo, PurePosixPath]] = []
    skipped_ignored = 0
    for info in archive.infolist():
        rel = _safe_member_path(info.filename)
        if rel is None:
            errors.append(f"unsafe path in archive: {info.filename!r} (absolute or containing '..')")
            continue
        if info.flag_bits & 0x1:
            errors.append(f"encrypted entries are not supported: {info.filename!r}")
            continue
        mode = (info.external_attr >> 16) & 0xFFFF
        if stat.S_ISLNK(mode):
            errors.append(f"symbolic links are not allowed: {info.filename!r}")
            continue
        if info.is_dir():
            continue
        if any(part in _IGNORED_DIRS for part in rel.parts[:-1]) or rel.name in _IGNORED_FILES or rel.suffix == ".pyc":
            skipped_ignored += 1
            continue
        if _is_env_file(rel.name):
            warnings.append(
                f"'{rel}' was removed: credentials are entered in AION and stored encrypted, never shipped in the package"
            )
            continue
        kept.append((info, rel))

    if errors:
        return errors, warnings
    if not kept:
        raise UploadError("the archive contains no files")
    if skipped_ignored:
        warnings.append(f"{skipped_ignored} cache/virtualenv/VCS file(s) were skipped")

    # A zip made with "compress folder" has one wrapper directory: unwrap it so the
    # entrypoint ends up at the package root.
    first_parts = {rel.parts[0] for _, rel in kept}
    if len(first_parts) == 1 and all(len(rel.parts) > 1 for _, rel in kept):
        kept = [(info, PurePosixPath(*rel.parts[1:])) for info, rel in kept]

    if len(kept) > settings.max_files():
        raise UploadError(f"too many files: {len(kept)} (limit {settings.max_files()})")
    declared_total = sum(info.file_size for info, _ in kept)
    if declared_total > settings.max_unpacked_bytes():
        raise UploadError(
            f"the extracted package would be {declared_total // (1024 * 1024)} MB "
            f"(limit {settings.max_unpacked_bytes() // (1024 * 1024)} MB)"
        )

    # Second pass: write files, counting real bytes (headers can lie in a zip bomb).
    dest.mkdir(parents=True, exist_ok=True)
    dest_resolved = dest.resolve()
    written = 0
    for info, rel in kept:
        target = (dest / Path(*rel.parts)).resolve()
        if dest_resolved not in target.parents:
            raise UploadError(f"unsafe path in archive: {info.filename!r}")
        target.parent.mkdir(parents=True, exist_ok=True)
        with archive.open(info) as src, open(target, "wb") as out:
            while True:
                chunk = src.read(1024 * 1024)
                if not chunk:
                    break
                written += len(chunk)
                if written > settings.max_unpacked_bytes():
                    raise UploadError("the extracted package exceeds the size limit")
                out.write(chunk)
    return errors, warnings


def _write_single_py(data: bytes, dest: Path) -> None:
    """Store a single uploaded ``.py`` as ``server.py`` (the default entrypoint)."""
    try:
        data.decode("utf-8")
    except UnicodeDecodeError:
        raise UploadError("the Python file must be UTF-8 text")
    dest.mkdir(parents=True, exist_ok=True)
    (dest / "server.py").write_bytes(data)


def _list_files(src: Path) -> List[Dict[str, Any]]:
    out = []
    for p in sorted(src.rglob("*")):
        if p.is_file():
            out.append({"path": p.relative_to(src).as_posix(), "size": p.stat().st_size})
    return out


# ───────────────────────── static analysis ─────────────────────────


def _is_environ(node: ast.AST) -> bool:
    """``os.environ`` or a bare ``environ`` (``from os import environ``)."""
    if isinstance(node, ast.Attribute) and node.attr == "environ":
        return isinstance(node.value, ast.Name) and node.value.id == "os"
    return isinstance(node, ast.Name) and node.id == "environ"


def _str_const(node: Optional[ast.AST]) -> Optional[str]:
    return node.value if isinstance(node, ast.Constant) and isinstance(node.value, str) else None


# Path fragments a server has no reason to touch: AION's data/config and system
# secrets. Matched against string constants passed to open()/Path().
_SENSITIVE_PATH_RE = re.compile(r"(^/app\b|^/proc\b|^/etc/|^/root\b|^/run/|\.env$|aion\.db|podman\.sock|docker\.sock)")


class _CodeScanner(ast.NodeVisitor):
    """Collect env-var reads, imports and review notes from one Python file."""

    def __init__(self, rel_path: str):
        self.rel_path = rel_path
        self.env_keys: Set[str] = set()
        self.imports: Set[str] = set()
        self.notes: List[Dict[str, Any]] = []

    def _note(self, node: ast.AST, severity: str, message: str) -> None:
        self.notes.append(
            {"file": self.rel_path, "line": getattr(node, "lineno", None), "severity": severity, "message": message}
        )

    def visit_Import(self, node: ast.Import) -> None:
        for alias in node.names:
            self.imports.add(alias.name.split(".")[0])
        self.generic_visit(node)

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:
        if node.level == 0 and node.module:
            self.imports.add(node.module.split(".")[0])
        self.generic_visit(node)

    def visit_Subscript(self, node: ast.Subscript) -> None:
        # os.environ["KEY"]
        if _is_environ(node.value):
            key = _str_const(node.slice)
            if key:
                self.env_keys.add(key)
            else:
                self._note(node, "info", "reads an environment variable with a computed name (cannot be checked)")
        self.generic_visit(node)

    def visit_Call(self, node: ast.Call) -> None:
        func = node.func
        first = node.args[0] if node.args else None
        # os.environ.get("KEY") / os.getenv("KEY") / getenv("KEY")
        is_env_get = isinstance(func, ast.Attribute) and func.attr in ("get", "pop", "setdefault") and _is_environ(func.value)
        is_getenv = (isinstance(func, ast.Attribute) and func.attr == "getenv") or (isinstance(func, ast.Name) and func.id == "getenv")
        if is_env_get or is_getenv:
            key = _str_const(first)
            if key:
                self.env_keys.add(key)
            elif first is not None:
                self._note(node, "info", "reads an environment variable with a computed name (cannot be checked)")
        # dict(os.environ) / os.environ.copy() / os.environ.items(): the whole environment.
        if isinstance(func, ast.Name) and func.id == "dict" and first is not None and _is_environ(first):
            self._note(node, "high", "copies the whole environment (dict(os.environ))")
        if isinstance(func, ast.Attribute) and func.attr in ("copy", "items", "keys", "values") and _is_environ(func.value):
            self._note(node, "high", f"reads the whole environment (os.environ.{func.attr}())")
        # Dynamic code execution.
        if isinstance(func, ast.Name) and func.id in ("eval", "exec", "compile", "__import__"):
            self._note(node, "high", f"executes dynamic code ({func.id})")
        # External commands.
        if isinstance(func, ast.Attribute) and isinstance(func.value, ast.Name):
            mod, attr = func.value.id, func.attr
            if mod == "subprocess":
                shell = any(k.arg == "shell" and isinstance(k.value, ast.Constant) and k.value.value is True for k in node.keywords)
                self._note(node, "critical" if shell else "high", f"runs external commands (subprocess.{attr}{', shell=True' if shell else ''})")
            elif mod == "os" and attr in ("system", "popen", "execv", "execve", "execvp", "spawnv", "fork", "kill"):
                self._note(node, "high", f"runs or controls processes (os.{attr})")
            elif mod in ("pickle", "marshal") and attr in ("load", "loads"):
                self._note(node, "medium", f"deserialises untrusted data ({mod}.{attr})")
            elif mod == "ctypes":
                self._note(node, "high", "uses native code (ctypes)")
        # File access to sensitive paths (string constants only).
        if isinstance(func, ast.Name) and func.id in ("open", "Path"):
            path = _str_const(first)
            if path and _SENSITIVE_PATH_RE.search(path):
                self._note(node, "high", f"accesses a system or AION file: {path!r}")
        self.generic_visit(node)

    def visit_For(self, node: ast.For) -> None:
        # for k in os.environ: ...
        if _is_environ(node.iter):
            self._note(node, "high", "iterates over the whole environment")
        self.generic_visit(node)


def _scan_code(src: Path) -> Tuple[Set[str], Set[str], List[Dict[str, Any]], List[str]]:
    """Scan every .py file: (env keys, imported top-level modules, notes, syntax errors)."""
    env_keys: Set[str] = set()
    imports: Set[str] = set()
    notes: List[Dict[str, Any]] = []
    syntax_errors: List[str] = []
    for py in sorted(src.rglob("*.py")):
        rel = py.relative_to(src).as_posix()
        try:
            tree = ast.parse(py.read_text(encoding="utf-8"), filename=rel)
        except (SyntaxError, UnicodeDecodeError) as exc:
            line = getattr(exc, "lineno", None)
            syntax_errors.append(f"{rel}{f':{line}' if line else ''}: {exc.__class__.__name__}: {getattr(exc, 'msg', exc)}")
            continue
        scanner = _CodeScanner(rel)
        scanner.visit(tree)
        env_keys |= scanner.env_keys
        imports |= scanner.imports
        notes.extend(scanner.notes)
    return env_keys, imports, notes, syntax_errors


def _shadowing_errors(src: Path) -> List[str]:
    """Top-level files/folders that would hide a standard-library or MCP module."""
    errors = []
    for p in sorted(src.iterdir()):
        name = p.name if p.is_dir() else (p.stem if p.suffix == ".py" else None)
        if name and name in _SHADOW_NAMES:
            kind = "folder" if p.is_dir() else "file"
            errors.append(
                f"the {kind} '{p.name}' hides the Python module '{name}' and would break the server: rename it"
            )
    return errors


# Normalised requirements file written into the package for the build container:
# requirements.txt as is, or the dependencies listed in pyproject.toml.
NORMALIZED_REQUIREMENTS = ".aion-requirements.txt"


def _declared_requirements(src: Path) -> Tuple[List[str], List[str]]:
    """Dependency specs of the package and errors: (requirements, errors).

    ``requirements.txt`` wins; otherwise ``[project].dependencies`` of
    ``pyproject.toml`` (the project itself is never built: that would run its build
    backend). Any package is accepted: it is installed and run inside the jail.
    """
    req_file = src / "requirements.txt"
    if req_file.is_file():
        lines = [
            line.strip()
            for line in req_file.read_text(encoding="utf-8", errors="replace").splitlines()
            if line.strip() and not line.strip().startswith("#")
        ]
        return lines, []
    pyproject = src / "pyproject.toml"
    if pyproject.is_file():
        import tomllib

        try:
            data = tomllib.loads(pyproject.read_text(encoding="utf-8"))
        except (tomllib.TOMLDecodeError, UnicodeDecodeError) as exc:
            return [], [f"pyproject.toml is not valid TOML: {exc}"]
        deps = (data.get("project") or {}).get("dependencies") or []
        return [str(d).strip() for d in deps if str(d).strip()], []
    return [], []


# ───────────────────────── review (manifest-dependent) ─────────────────────────


def _review(staged: StagedUpload, src: Path) -> None:
    """(Re)compute errors, warnings and checks that depend on the manifest.

    Run after extraction and again when the admin submits the manifest form.
    """
    errors = list(staged.extract_errors)
    warnings = list(staged.extract_warnings)

    env_keys, imports, notes, syntax_errors = _scan_code(src)
    errors.extend(f"syntax error in {e}" for e in syntax_errors)
    errors.extend(_shadowing_errors(src))
    staged.env_used = sorted(env_keys)
    staged.review_notes = notes[:MAX_NOTES]
    if len(notes) > MAX_NOTES:
        warnings.append(f"{len(notes) - MAX_NOTES} more review notes not shown")
    # Dependencies: any package is accepted; the verification step installs them in
    # an isolated build container and the probe proves the server really starts.
    staged.missing_modules = []
    staged.requirements, req_errors = _declared_requirements(src)
    errors.extend(req_errors)
    staged.has_requirements = bool(staged.requirements)
    normalized = src / NORMALIZED_REQUIREMENTS
    if staged.requirements:
        normalized.write_text("\n".join(staged.requirements) + "\n", encoding="utf-8")
    else:
        normalized.unlink(missing_ok=True)
    # Any change to the package review invalidates a previous verification.
    staged.build = {}
    readme = src / "README.md"
    staged.readme = readme.read_text(encoding="utf-8", errors="replace")[:README_MAX_CHARS] if readme.is_file() else None

    manifest = Manifest.model_validate(staged.manifest) if staged.manifest else None
    staged.update_of = None
    if manifest is None:
        staged.entrypoint = "server.py" if (src / "server.py").is_file() else None
        staged.env_check = {"undeclared": sorted(env_keys - PROVIDED_ENV), "unused": []}
    else:
        staged.entrypoint = manifest.entrypoint
        if not (src / manifest.entrypoint).is_file():
            errors.append(f"entrypoint '{manifest.entrypoint}' not found in the package")
        # Variables check: what the code reads vs what the manifest provides.
        declared = set(manifest.env) | {f.key for f in manifest.credentials.fields}
        undeclared = sorted(env_keys - declared - PROVIDED_ENV)
        unused = sorted(declared - env_keys)
        staged.env_check = {"undeclared": undeclared, "unused": unused}
        if undeclared:
            warnings.append(
                "the code reads variables not declared in the manifest (they will be empty): " + ", ".join(undeclared)
            )
        if unused:
            warnings.append(
                "declared in the manifest but never read with a constant name in the code: " + ", ".join(unused)
            )
        # Slug: free, or an update of an existing custom server.
        conflict = slug_conflict(manifest.slug)
        if conflict:
            errors.append(conflict)
        else:
            from ..mcp_manager import mcp_manager

            existing = mcp_manager._registry.get(manifest.slug)
            if is_custom_config(existing):
                current = str(existing["aion_custom"].get("version") or "")
                staged.update_of = {
                    "slug": manifest.slug,
                    "current_version": current,
                    "same_version": current == manifest.version,
                }
                if current == manifest.version:
                    warnings.append(
                        f"version {manifest.version} is already installed: activating replaces it (bump 'version' to keep history)"
                    )
    if staged.entrypoint is None:
        errors.append("server.py not found at the package root: add it or set 'entrypoint' in aion-mcp.yaml")

    staged.errors = list(dict.fromkeys(errors))
    staged.warnings = list(dict.fromkeys(warnings))


